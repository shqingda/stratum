import json, os, collections

M = collections.OrderedDict()
def m(key, zh, en, **ph):
    assert key not in M, key
    if "{count, plural" in en and "count" not in ph:
        ph["count"] = "int"
    M[key] = (zh, en, ph)

P = lambda one, other: "{count, plural, one {" + one + "} other {" + other + "}}"

